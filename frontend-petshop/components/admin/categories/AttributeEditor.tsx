'use client';

import { useCallback, useEffect, useState, type FormEvent } from 'react';
import type { CategoryAttribute } from '../../../lib/types';
import { FormAlert } from '../../ui/FormAlert';
import { TextField } from '../../ui/TextField';
import { categoryApi, refreshStorefront } from './adminCategoryApi';

type Attribute = CategoryAttribute & { attributeType: string };
const TYPE_LABELS: Record<string, string> = { text: 'Chữ', number: 'Số' };

// [] when the list cannot be read: the form still works and the owner can retry by reopening.
async function fetchAttributes(categoryId: string): Promise<Attribute[]> {
  const res = await categoryApi<Attribute[]>(`/${categoryId}/attributes`);
  return res.data ?? [];
}

// Spec fields of a category ("Thông số"): they become inputs on the product form and the spec table
// on product pages. The key is generated by the backend from the label ("Trọng lượng" → trong_luong).
export function AttributeEditor({ categoryId, categoryName }: { categoryId: string; categoryName: string }) {
  const [rows, setRows] = useState<Attribute[] | null>(null);
  const [label, setLabel] = useState('');
  const [type, setType] = useState('text');
  const [alert, setAlert] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);

  const load = useCallback(async () => setRows(await fetchAttributes(categoryId)), [categoryId]);

  useEffect(() => {
    let active = true;
    fetchAttributes(categoryId).then((next) => active && setRows(next));
    return () => {
      active = false;
    };
  }, [categoryId]);

  async function add(event: FormEvent<HTMLFormElement>) {
    event.preventDefault();
    if (!label.trim()) return setAlert('Nhập tên thông số.');
    setBusy(true);
    const res = await categoryApi(`/${categoryId}/attributes`, { method: 'POST', body: JSON.stringify({ attributeLabel: label.trim(), attributeType: type }) });
    setBusy(false);
    if (res.error) return setAlert(res.error.message);
    setLabel('');
    setAlert(null);
    await Promise.all([load(), refreshStorefront()]);
  }

  async function remove(row: Attribute) {
    if (!window.confirm(`Xoá thông số “${row.attributeLabel}”? Giá trị đã nhập ở sản phẩm sẽ không còn hiện.`)) return;
    setBusy(true);
    const res = await categoryApi(`/${categoryId}/attributes/${row.id}`, { method: 'DELETE' });
    setBusy(false);
    if (res.error) return setAlert(res.error.message);
    await Promise.all([load(), refreshStorefront()]);
  }

  return (
    <section aria-labelledby="attr-title" className="flex flex-col gap-3 border-t border-line pt-4">
      <h3 id="attr-title" className="font-extrabold">Thông số của “{categoryName}”</h3>
      <FormAlert message={alert} />
      {rows === null ? (
        <div aria-busy="true" aria-label="Đang tải thông số" className="h-12 animate-pulse rounded-card bg-surface-alt" />
      ) : rows.length === 0 ? (
        <p className="text-sm text-muted">Chưa có thông số nào.</p>
      ) : (
        <ul className="flex flex-col gap-2">
          {rows.map((r) => (
            <li key={r.id} className="flex items-center justify-between gap-3 rounded-card bg-surface-alt px-3 py-2">
              <span className="min-w-0 break-words text-sm"><b className="text-ink">{r.attributeLabel}</b> <span className="text-muted">{r.attributeKey} · {TYPE_LABELS[r.attributeType] ?? r.attributeType}</span></span>
              <button type="button" disabled={busy} onClick={() => remove(r)} aria-label={`Xoá thông số ${r.attributeLabel}`}
                className="grid size-11 shrink-0 place-items-center rounded-full border border-line text-pink-ink disabled:opacity-40">✕</button>
            </li>
          ))}
        </ul>
      )}
      <form onSubmit={add} noValidate className="flex flex-col gap-2 sm:flex-row sm:items-end">
        <TextField name="attributeLabel" label="Thông số mới" placeholder="Vd. Trọng lượng" maxLength={60} value={label} className="flex-1"
          onChange={(e) => setLabel(e.target.value)} />
        <select aria-label="Kiểu dữ liệu" value={type} onChange={(e) => setType(e.target.value)} className="min-h-12 rounded-[var(--radius-sm)] border border-line bg-surface px-3 text-base">
          <option value="text">Chữ</option>
          <option value="number">Số</option>
        </select>
        <button type="submit" disabled={busy} className="min-h-12 rounded-full border border-brand-ink px-5 font-bold text-brand-ink disabled:opacity-60">Thêm</button>
      </form>
    </section>
  );
}
